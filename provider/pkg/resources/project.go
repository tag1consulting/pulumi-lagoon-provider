// Project delete wait settings. These are variables so tests can shorten them.
// infer.DeleteRequest does not expose the delete timeout. A customTimeouts.delete reaches
// Delete only as a deadline on ctx, so the shorter of that deadline and projectDeleteTimeout wins.
var (
	projectDeleteTimeout   = 15 * time.Minute
	projectDeleteBaseDelay = 5 * time.Second
	projectDeleteMaxDelay  = 30 * time.Second
	// projectDeleteStallTimeout ends the wait early when none of the active environments has
	// gone away for this long. Lagoon removed 6 environments about 50 seconds apart in the
	// report behind #313, so this leaves a wide margin.
	projectDeleteStallTimeout = 5 * time.Minute
)

// Project manages a Lagoon project resource.
type Project struct{}

// ProjectArgs are the inputs for a Lagoon project.
type ProjectArgs struct {
	Name                    string  `pulumi:"name"`
	GitURL                  string  `pulumi:"gitUrl"`
	DeploytargetID          int     `pulumi:"deploytargetId"`
	ProductionEnvironment   *string `pulumi:"productionEnvironment,optional"`
	Branches                *string `pulumi:"branches,optional"`
	Pullrequests            *string `pulumi:"pullrequests,optional"`
	OpenshiftProjectPattern *string `pulumi:"openshiftProjectPattern,optional"`
	AutoIdle                *int    `pulumi:"autoIdle,optional"`
	StorageCalc             *int    `pulumi:"storageCalc,optional"`
}

// ProjectState is the full state of a Lagoon project.
type ProjectState struct {
	ProjectArgs
	LagoonID  int    `pulumi:"lagoonId"`
	PublicKey string `pulumi:"publicKey"`
	Created   string `pulumi:"created"`
}

// WireDependencies tells infer which inputs affect which outputs during a preview.
// See DeployTarget.WireDependencies for the reason (issue #305). Only the name, which forces a
// replace, can change the Lagoon project ID.
func (r *Project) WireDependencies(f infer.FieldSelector, args *ProjectArgs, state *ProjectState) {
	f.OutputField(&state.LagoonID).DependsOn(f.InputField(&args.Name).Computed())
	// Wiring any dependency turns off infer's default flow for all outputs, so restate it.
	f.OutputField(&state.PublicKey).DependsOn(f.InputField(args).Computed())
	f.OutputField(&state.Created).DependsOn(f.InputField(args).Computed())
}

// Annotate sets the resource token and field descriptions.
func (r *Project) Annotate(a infer.Annotator) {
	a.SetToken("lagoon", "Project")
	a.Describe(&r, "Manages a Lagoon project (application/site).")
}

func (a *ProjectArgs) Annotate(an infer.Annotator) {
	an.Describe(&a.Name, "The project name. Must be unique, lowercase alphanumeric with hyphens.")
	an.Describe(&a.GitURL, "The Git repository URL (SSH or HTTPS format).")
	an.Describe(&a.DeploytargetID, "The deploy target (Kubernetes cluster) ID.")
	an.Describe(&a.ProductionEnvironment, "Name of the production branch/environment.")
	an.Describe(&a.Branches, "Regex pattern for branches to deploy.")
	an.Describe(&a.Pullrequests, "Regex pattern for pull requests to deploy.")
	an.Describe(&a.OpenshiftProjectPattern, "Namespace pattern for the project on the cluster.")
	an.Describe(&a.AutoIdle, "Whether to auto-idle environments (1=yes, 0=no).")
	an.Describe(&a.StorageCalc, "Whether to calculate storage (1=yes, 0=no).")
}

func (s *ProjectState) Annotate(a infer.Annotator) {
	a.Describe(&s.LagoonID, "The Lagoon-assigned numeric ID of the project.")
	a.Describe(&s.PublicKey, "The SSH public deploy key generated by Lagoon. Add this to the Git repository to grant Lagoon read access.")
	a.Describe(&s.Created, "The creation timestamp of the project.")
}

// Create creates a new Lagoon project.
func (r *Project) Create(ctx context.Context, req infer.CreateRequest[ProjectArgs]) (infer.CreateResponse[ProjectState], error) {
	c := clientFor(ctx)

	input := map[string]any{
		"name":      req.Inputs.Name,
		"gitUrl":    req.Inputs.GitURL,
		"openshift": req.Inputs.DeploytargetID,
	}
	setOptional(input, "productionEnvironment", req.Inputs.ProductionEnvironment)
	setOptional(input, "branches", req.Inputs.Branches)
	setOptional(input, "pullrequests", req.Inputs.Pullrequests)
	setOptional(input, "openshiftProjectPattern", req.Inputs.OpenshiftProjectPattern)
	setOptionalInt(input, "autoIdle", req.Inputs.AutoIdle)
	setOptionalInt(input, "storageCalc", req.Inputs.StorageCalc)

	if req.DryRun {
		return infer.CreateResponse[ProjectState]{
			ID:     "preview-id",
			Output: ProjectState{ProjectArgs: req.Inputs},
		}, nil
	}

	project, err := c.CreateProject(ctx, input)
	if err != nil {
		if client.IsDuplicateEntry(err) {
			return infer.CreateResponse[ProjectState]{}, fmt.Errorf("project %q already exists: use pulumi import to bring it under management", req.Inputs.Name)
		}
		return infer.CreateResponse[ProjectState]{}, fmt.Errorf("failed to create project: %w", err)
	}

	return infer.CreateResponse[ProjectState]{
		ID: strconv.Itoa(project.ID),
		Output: ProjectState{
			ProjectArgs: req.Inputs,
			LagoonID:    project.ID,
			PublicKey:   project.PublicKey,
			Created:     project.Created,
		},
	}, nil
}

// Update updates an existing Lagoon project.
func (r *Project) Update(ctx context.Context, req infer.UpdateRequest[ProjectArgs, ProjectState]) (infer.UpdateResponse[ProjectState], error) {
	c := clientFor(ctx)

	input := map[string]any{
		"gitUrl":    req.Inputs.GitURL,
		"openshift": req.Inputs.DeploytargetID,
	}
	setOptional(input, "productionEnvironment", req.Inputs.ProductionEnvironment)
	setOptional(input, "branches", req.Inputs.Branches)
	setOptional(input, "pullrequests", req.Inputs.Pullrequests)
	setOptional(input, "openshiftProjectPattern", req.Inputs.OpenshiftProjectPattern)
	setOptionalInt(input, "autoIdle", req.Inputs.AutoIdle)
	setOptionalInt(input, "storageCalc", req.Inputs.StorageCalc)

	if req.DryRun {
		return infer.UpdateResponse[ProjectState]{
			Output: ProjectState{
				ProjectArgs: req.Inputs,
				LagoonID:    req.State.LagoonID,
				PublicKey:   req.State.PublicKey,
				Created:     req.State.Created,
			},
		}, nil
	}

	updated, err := c.UpdateProject(ctx, req.State.LagoonID, input)
	if err != nil {
		return infer.UpdateResponse[ProjectState]{}, fmt.Errorf("failed to update project: %w", err)
	}

	publicKey := updated.PublicKey
	if publicKey == "" {
		publicKey = req.State.PublicKey
	}

	return infer.UpdateResponse[ProjectState]{
		Output: ProjectState{
			ProjectArgs: req.Inputs,
			LagoonID:    req.State.LagoonID,
			PublicKey:   publicKey,
			Created:     req.State.Created,
		},
	}, nil
}

// Delete deletes a Lagoon project.
func (r *Project) Delete(ctx context.Context, req infer.DeleteRequest[ProjectState]) (infer.DeleteResponse, error) {
	c := clientFor(ctx)
	name := req.State.Name

	// Lagoon removes environments asynchronously, so deleteProject can be refused
	// while a previous environment delete is still running. Retry only that error.
	// Lagoon does not say whether a removal is running: an environment keeps its active state
	// until the cluster confirms the removal. So the wait ends early only when the list of
	// active environments stops getting shorter, and otherwise at the overall timeout.
	start := time.Now()
	deadline := start.Add(projectDeleteTimeout)
	delay := projectDeleteBaseDelay
	var progress environmentProgress
	var remaining []string
	warnedQuery := false
	for attempt := 1; ; attempt++ {
		err := c.DeleteProject(ctx, name)
		if err == nil {
			if attempt > 1 {
				p.GetLogger(ctx).Infof("Project %s: deleted after %d attempts in %s", name, attempt, time.Since(start).Round(time.Second))
			}
			return infer.DeleteResponse{}, nil
		}
		// Treat "not found" as success — resource is already gone
		if errors.Is(err, client.ErrNotFound) {
			return infer.DeleteResponse{}, nil
		}
		if !client.IsEnvironmentsRemaining(err) {
			return infer.DeleteResponse{}, fmt.Errorf("failed to delete project: %w", err)
		}

		// Listing the environments is best effort. Without it the wait only has the overall timeout.
		names, listErr := c.GetProjectEnvironmentNames(ctx, name)
		switch {
		case listErr == nil:
			remaining = names
			progress.observe(names, time.Now())
		case !warnedQuery && !errors.Is(listErr, client.ErrNotFound):
			warnedQuery = true
			p.GetLogger(ctx).Warningf("Project %s: could not list the project's environments, so the wait cannot end early: %v", name, listErr)
		}

		elapsed := time.Since(start).Round(time.Second)
		if progress.stalled(time.Now(), projectDeleteStallTimeout) {
			return infer.DeleteResponse{}, fmt.Errorf(
				"failed to delete project: project %q still has %d active environments%s, and the list has not gone down for %s (%d attempts in %s). "+
					"Pulumi does not remove environments that it does not manage. "+
					"Remove them in Lagoon, then run `pulumi up` again: %w",
				name, len(remaining), describeEnvironments(remaining), projectDeleteStallTimeout, attempt, elapsed, err)
		}
		if !time.Now().Add(delay).Before(deadline) {
			return infer.DeleteResponse{}, fmt.Errorf(
				"failed to delete project: project %q still has active environments%s after %d attempts in %s. "+
					"Remove the remaining environments in Lagoon (for example, environments that Pulumi does not manage), "+
					"then run `pulumi up` again: %w", name, describeEnvironments(remaining), attempt, elapsed, err)
		}
		p.GetLogger(ctx).Infof("Project %s: project still has environments%s, retrying delete in %s (attempt %d)", name, describeEnvironments(remaining), delay, attempt)

		timer := time.NewTimer(delay)
		select {
		case <-ctx.Done():
			timer.Stop()
			return infer.DeleteResponse{}, fmt.Errorf(
				"delete of project %q stopped after %d attempts in %s while environments still existed%s (%w), last Lagoon error: %v",
				name, attempt, elapsed, describeEnvironments(remaining), ctx.Err(), err)
		case <-timer.C:
		}
		delay = nextProjectDeleteDelay(delay)
	}
}

// environmentProgress tracks whether the active environments of a project are going away.
type environmentProgress struct {
	seen  map[string]bool
	since time.Time // last time an environment disappeared, or the first observation
}

// observe records the active environments. Progress is any environment seen earlier that is
// gone now, or an empty list.
func (e *environmentProgress) observe(names []string, now time.Time) {
	current := make(map[string]bool, len(names))
	for _, n := range names {
		current[n] = true
	}
	if e.seen == nil {
		e.since = now
	} else {
		for n := range e.seen {
			if !current[n] {
				e.since = now
				break
			}
		}
	}
	if len(current) == 0 {
		e.since = now
	}
	e.seen = current
}

// stalled reports whether no environment has gone away for the timeout.
func (e *environmentProgress) stalled(now time.Time, timeout time.Duration) bool {
	return e.seen != nil && now.Sub(e.since) >= timeout
}

// describeEnvironments formats up to 10 environment names for an error or log line.
func describeEnvironments(names []string) string {
	if len(names) == 0 {
		return ""
	}
	const limit = 10
	shown := names
	more := ""
	if len(names) > limit {
		shown = names[:limit]
		more = fmt.Sprintf(" and %d more", len(names)-limit)
	}
	return " (" + strings.Join(shown, ", ") + more + ")"
}

// nextProjectDeleteDelay doubles the delay, caps it at projectDeleteMaxDelay, then adds up to 25% jitter.
// The jitter is added after the cap, so the result can exceed projectDeleteMaxDelay by up to 25%.
func nextProjectDeleteDelay(d time.Duration) time.Duration {
	d *= 2
	if d > projectDeleteMaxDelay {
		d = projectDeleteMaxDelay
	}
	if quarter := int64(d) / 4; quarter > 0 {
		d += time.Duration(rand.Int63n(quarter)) //nolint:gosec // non-crypto jitter
	}
	return d
}

// Read reads a Lagoon project for import/refresh.
func (r *Project) Read(ctx context.Context, req infer.ReadRequest[ProjectArgs, ProjectState]) (infer.ReadResponse[ProjectArgs, ProjectState], error) {
	c := clientFor(ctx)

	lagoonID, err := strconv.Atoi(req.ID)
	if err != nil {
		return infer.ReadResponse[ProjectArgs, ProjectState]{}, fmt.Errorf("invalid project ID '%s': must be numeric", req.ID)
	}

	project, err := c.GetProjectByID(ctx, lagoonID)
	if err != nil {
		// Return empty ID to signal the resource was deleted from Lagoon
		if errors.Is(err, client.ErrNotFound) {
			return infer.ReadResponse[ProjectArgs, ProjectState]{}, nil
		}
		return infer.ReadResponse[ProjectArgs, ProjectState]{}, fmt.Errorf("failed to read project: %w", err)
	}

	args := ProjectArgs{
		Name:           project.Name,
		GitURL:         project.GitURL,
		DeploytargetID: project.OpenshiftID,
	}
	if project.ProductionEnvironment != "" {
		args.ProductionEnvironment = &project.ProductionEnvironment
	}
	if project.Branches != "" {
		args.Branches = &project.Branches
	}
	if project.Pullrequests != "" {
		args.Pullrequests = &project.Pullrequests
	}
	if project.OpenshiftProjectPattern != "" {
		args.OpenshiftProjectPattern = &project.OpenshiftProjectPattern
	}
	args.AutoIdle = project.AutoIdle
	args.StorageCalc = project.StorageCalc

	st := ProjectState{
		ProjectArgs: args,
		LagoonID:    project.ID,
		PublicKey:   project.PublicKey,
		Created:     project.Created,
	}

	return infer.ReadResponse[ProjectArgs, ProjectState]{
		ID:     req.ID,
		Inputs: args,
		State:  st,
	}, nil
}

// deployTargetConfigPlaceholder is the literal string the Lagoon API writes into
// a project's branches/pullrequests columns as soon as any DeployTargetConfig is
// attached to that project (see uselagoon/lagoon
// services/api/src/resources/deploytargetconfig/sql.ts,
// updateProjectBranchPullrequestRegex, invoked from the addDeployTargetConfig
// resolver). From that point on, routing is controlled per-deploy-target-config
// and the project-level fields are cosmetic; the API always returns this exact
// same string for both fields regardless of what was last configured, so a
// refresh followed by a preview would otherwise show a permanent, unresolvable
// diff against the user's desired regex. See issue #270.
const deployTargetConfigPlaceholder = "This project is configured with DeployTargets"

// Diff computes the diff between old and new project state.
func (r *Project) Diff(ctx context.Context, req infer.DiffRequest[ProjectArgs, ProjectState]) (infer.DiffResponse, error) {
	diff := map[string]p.PropertyDiff{}

	// name is forceNew
	if req.Inputs.Name != req.State.Name {
		diff["name"] = p.PropertyDiff{Kind: p.UpdateReplace}
	}

	// These can be updated in place
	if req.Inputs.GitURL != req.State.GitURL {
		diff["gitUrl"] = p.PropertyDiff{Kind: p.Update}
	}
	if req.Inputs.DeploytargetID != req.State.DeploytargetID {
		diff["deploytargetId"] = p.PropertyDiff{Kind: p.Update}
	}
	// All pointer fields use nil-means-unmanaged semantics: if the user's
	// input is nil they don't want to manage the field, so skip the diff even
	// if the API returns a value.  This prevents spurious updates on refresh.
	if req.Inputs.ProductionEnvironment != nil && ptrDiffers(req.Inputs.ProductionEnvironment, req.State.ProductionEnvironment) {
		diff["productionEnvironment"] = p.PropertyDiff{Kind: p.Update}
	}
	// The state's placeholder is not real drift: the API always overwrites
	// branches/pullrequests with this exact string once a DeployTargetConfig
	// exists, no matter what regex was last applied, so comparing it against the
	// user's desired input would flag an update on every single preview/up.
	stateBranchesIsPlaceholder := req.State.Branches != nil && *req.State.Branches == deployTargetConfigPlaceholder
	if req.Inputs.Branches != nil && !stateBranchesIsPlaceholder && ptrDiffers(req.Inputs.Branches, req.State.Branches) {
		diff["branches"] = p.PropertyDiff{Kind: p.Update}
	}
	statePullrequestsIsPlaceholder := req.State.Pullrequests != nil && *req.State.Pullrequests == deployTargetConfigPlaceholder
	if req.Inputs.Pullrequests != nil && !statePullrequestsIsPlaceholder && ptrDiffers(req.Inputs.Pullrequests, req.State.Pullrequests) {
		diff["pullrequests"] = p.PropertyDiff{Kind: p.Update}
	}
	if req.Inputs.OpenshiftProjectPattern != nil && ptrDiffers(req.Inputs.OpenshiftProjectPattern, req.State.OpenshiftProjectPattern) {
		diff["openshiftProjectPattern"] = p.PropertyDiff{Kind: p.Update}
	}
	if req.Inputs.AutoIdle != nil && ptrIntDiffers(req.Inputs.AutoIdle, req.State.AutoIdle) {
		diff["autoIdle"] = p.PropertyDiff{Kind: p.Update}
	}
	if req.Inputs.StorageCalc != nil && ptrIntDiffers(req.Inputs.StorageCalc, req.State.StorageCalc) {
		diff["storageCalc"] = p.PropertyDiff{Kind: p.Update}
	}

	return p.DiffResponse{
		HasChanges:          len(diff) > 0,
		DetailedDiff:        diff,
		DeleteBeforeReplace: true,
	}, nil
}

